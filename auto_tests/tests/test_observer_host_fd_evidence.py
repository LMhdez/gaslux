def _process_fingerprint(pid: int) -> ProcessSeal:
    """Real /proc identity of a fixture process, NOT a QEMU process."""
    proc = Path("/proc") / str(pid)
    raw = (proc / "stat").read_text()
    fields = raw[raw.rfind(")") + 2 :].split()
    exe = (proc / "exe").stat()
    return ProcessSeal(
        pid,
        proc.stat().st_uid,
        int(fields[19]),
        hashlib.sha256((proc / "cmdline").read_bytes()).hexdigest(),
        exe.st_dev,
        exe.st_ino,
    )


@pytest.fixture
def child_fd(tmp_path, synthetic_image_writer):
    image = tmp_path / "disk.img"
    synthetic_image_writer(image)
    # A child process opens a *real* read-only file descriptor. No QEMU.
    command = (
        "import os,sys,time;fd=os.open(sys.argv[1],os.O_RDONLY);print(fd,flush=True);time.sleep(25)"
    )
    process = subprocess.Popen(
        [sys.executable, "-c", command, str(image)],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        close_fds=True,
    )
    try:
        assert process.stdout is not None
        fd = int(process.stdout.readline().strip())
        stat = image.stat()
        seal = _process_fingerprint(process.pid)
        pins = HostPins(
            process=seal,
            qemu_executable_sha256="a" * 64,
            transaction_id="lab-transaction",
            vm_uuid="vm-synthetic-uuid",
            challenge="synthetic-repeated-or-new-challenge",
            device_name="virtio-disk",
            serial="LAB-ONLY-SERIAL",
            fd_number=fd,
            media_path=image,
            expected_dev=stat.st_dev,
            expected_inode=stat.st_ino,
            expected_size=stat.st_size,
        )
        yield image, pins
    finally:
        process.terminate()
        try:
            process.communicate(timeout=3)
        except subprocess.TimeoutExpired:
            process.kill()
            process.communicate(timeout=3)


def _qmp(pins: HostPins) -> list[dict]:
    return [
        {
            "device": pins.device_name,
            "inserted": {
                "file": str(pins.media_path),
                "ro": True,
                "image": {"filename": str(pins.media_path), "format": "raw"},
            },
        }
    ]


def test_real_host_fd_and_canonical_gpt_286(child_fd, canonical_gate):
    image, pins = child_fd
    reading = observe_descriptor(pins)
    assert reading["assurance"] == "LOCALLY_MEASURED"
    assert reading["readMethod"] == "proc-fd-reopened-readonly-pread"
    assert reading["fileInode"] == image.stat().st_ino
    gpt = measure_gpt_from_proc_fd(pins, canonical_gate)
    assert gpt["snapshot"]["partitionStyle"] == "GPT"
    assert gpt["snapshot"]["logicalSectorSizeBytes"] == 512
    assert len(gpt["snapshot"]["partitions"]) == 1
    assert set(gpt["regions"]) == {"primaryHeader", "primaryArray", "backupHeader", "backupArray"}
    with image.open("rb") as file:
        first = file.read(512)
    assert reading["firstSectorSha256"] == hashlib.sha256(first).hexdigest()
    assert gpt["snapshot"]["sizeBytes"] == pins.expected_size
    assert all(len(sample["sha256"]) == 64 for sample in gpt["regions"].values())


def test_host_fd_does_not_change_original_child_file_offset(child_fd, canonical_gate):
    _, pins = child_fd
    # Child's original FD offset remains untouched by /proc reopening/pread.
    info = Path("/proc") / str(pins.process.pid) / "fdinfo" / str(pins.fd_number)
    before = info.read_text()
    measure_gpt_from_proc_fd(pins, canonical_gate)
    after = info.read_text()
    assert [s for s in before.splitlines() if s.startswith("pos:")] == [
        s for s in after.splitlines() if s.startswith("pos:")
    ]


@pytest.mark.parametrize("mutation", ["pid", "fd", "inode", "dev", "size", "start", "executable"])
def test_wrong_identity_is_refused(child_fd, mutation):
    _, pins = child_fd
    if mutation == "start":
        with pytest.raises(HostEvidenceRefused, match="START_TICKS"):
            require_process_identity(
                pins.process, replace(pins.process, start_ticks=pins.process.start_ticks + 1)
            )
        return
    if mutation == "executable":
        with pytest.raises(HostEvidenceRefused, match="START_TICKS"):
            require_process_identity(
                pins.process, replace(pins.process, executable_ino=pins.process.executable_ino + 1)
            )
        return
    overrides = {
        "pid": {"process": replace(pins.process, pid=99999999)},
        "fd": {"fd_number": pins.fd_number + 1},
        "inode": {"expected_inode": pins.expected_inode + 1},
        "dev": {"expected_dev": pins.expected_dev + 1},
        "size": {"expected_size": pins.expected_size + 512},
    }
    with pytest.raises(HostEvidenceRefused):
        observe_descriptor(replace(pins, **overrides[mutation]))


