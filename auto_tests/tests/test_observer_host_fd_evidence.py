@pytest.mark.parametrize(
    "change", ["path", "device", "format", "ro", "vm", "serial", "ambiguous", "missing"]
)
def test_claimed_qmp_or_fd_device_mismatch_refuses(child_fd, change):
    _, pins = child_fd
    descriptor = observe_descriptor(pins)
    blocks = _qmp(pins)
    if change == "path":
        blocks[0]["inserted"]["file"] = "/tmp/unrelated.raw"
    elif change == "device":
        blocks[0]["device"] = "other-drive"
    elif change == "format":
        blocks[0]["inserted"]["image"]["format"] = "qcow2"
    elif change == "ro":
        blocks[0]["inserted"]["ro"] = False
    elif change == "vm":
        blocks[0]["vmUuid"] = "different-vm"
    elif change == "serial":
        blocks[0]["inserted"]["serial"] = "wrong-serial"
    elif change == "ambiguous":
        blocks.append(copy.deepcopy(blocks[0]))
    else:
        blocks = []
    with pytest.raises(HostEvidenceRefused):
        correlate_qmp_fd(pins, descriptor, blocks)


