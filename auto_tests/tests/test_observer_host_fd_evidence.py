def test_workflow_is_strictly_synthetic_no_qemu_launch():
    workflow = yaml.load(WORKFLOW.read_text(encoding="utf-8"), Loader=yaml.BaseLoader)
    assert set(workflow["on"]) == {"push"}
    assert workflow["permissions"] == {"contents": "read"}
    assert set(workflow["jobs"]) == {"host-fd-contracts"}
    job = workflow["jobs"]["host-fd-contracts"]
    assert job["runs-on"] == "ubuntu-24.04"
    steps = job["steps"]
    for step in steps:
        if "uses" in step and "checkout" in step["uses"]:
            assert step["with"]["persist-credentials"] == "false"
        if "run" in step:
            # Only bash syntax/lint or pytest; neither QEMU nor guest commands.
            subprocess.run(
                ["bash", "-n"], input=step["run"], text=True, capture_output=True, check=True
            )
            assert "qemu-system" not in step["run"]
            assert "libguestfs" not in step["run"]
    assert any(
        step.get("with", {}).get("ref") == "9aed36cfdb8c09a461dc38811c326c54180273de"
        for step in steps
    )


