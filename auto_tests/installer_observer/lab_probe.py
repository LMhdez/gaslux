# Only scratch artifacts generated by this script may ever be attached.
RESOLUTIONS = ((720, 400), (640, 480), (800, 600), (1024, 768))


def _command(args: list[str]) -> None:
    subprocess.run(args, check=True, timeout=30, capture_output=True)


def _outside_client(path: Path, *, different_uid: bool) -> int:
    """A separate process attempts only connect(2); no RFB/QMP messages."""
    code = (
        "import socket,sys;"
        "s=socket.socket(socket.AF_UNIX);"
        "p=sys.argv[1];"
        "try_code=0;"
        "exec('try:\\n s.connect(p)\\nexcept PermissionError:\\n try_code=13"
        "\\nexcept OSError:\\n try_code=14');"
        "s.close();sys.exit(try_code)"
    )
    command = ["/usr/bin/python3", "-c", code, str(path)]
    if different_uid:
        command = ["sudo", "-n", "-u", "nobody", *command]
    try:
        result = subprocess.run(command, timeout=8, capture_output=True, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise Refusal("External Unix socket probe unavailable") from exc
    return result.returncode


def _one(evidence_root: Path) -> dict:
    run_id = str(uuid.uuid4())
    with tempfile.TemporaryDirectory(prefix="observer-qemu-") as temp:
        sandbox = Path(temp)
        iso = sandbox / "fixture.iso"
        iso.write_bytes((b"GASLUX-OBSERVE-ONLY-TEST-MEDIA" + bytes(64)) * 256)
        identity = DistributionIdentity(
            "fixture-not-q4os", "0", digest(iso.read_bytes()), iso.stat().st_size
        )
        # Verify the source in full before starting any QEMU process.
        identity.verify_iso(iso)
        cow = sandbox / "empty.qcow2"
        _command(["qemu-img", "create", "-f", "qcow2", str(cow), "64M"])
        snapshot = "snap-" + run_id
        _command(["qemu-img", "snapshot", "-c", snapshot, str(cow)])
        authority = LabAuthority(run_id, identity, "lab-probe-v1", snapshot, True, False)
        sandbox.chmod(0o700)
        qmp = sandbox / "qmp.sock"
        vnc = sandbox / "rfb.sock"
        port = 0  # no TCP VNC listener
        cmd = [
            "qemu-system-x86_64",
            "-no-user-config",
            "-nodefaults",
            "-machine",
            "pc",
            "-accel",
            "tcg",
            "-m",
            "128",
            "-vga",
            "std",
            "-display",
            "none",
            "-monitor",
            "none",
            "-serial",
            "none",
            "-net",
            "none",
            "-vnc",
            f"unix:{vnc}",
            "-qmp",
            f"unix:{qmp},server=on,wait=off",
            "-drive",
            f"file={cow},if=virtio,format=qcow2,cache=none",
            "-drive",
            f"file={iso},media=cdrom,format=raw,readonly=on",
            "-boot",
            "order=d",
        ]
        proc = subprocess.Popen(
            cmd, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE
        )
        report = None
        location = None
        endpoints = ()
        try:
            deadline = time.monotonic() + 25
            while (
                (not qmp.exists() or not vnc.exists())
                and time.monotonic() < deadline
                and proc.poll() is None
            ):
                time.sleep(0.1)
            if proc.poll() is not None or not qmp.exists() or not vnc.exists():
                raise Refusal("QEMU did not expose its private QMP endpoint")
            # QEMU creates sockets in our inaccessible-to-other-UID directory.
            # Restrict endpoint mode as an additional defence, not an isolation proof.
            qmp.chmod(0o600)
            vnc.chmod(0o600)
            endpoints = (seal_endpoint(qmp, os.geteuid()), seal_endpoint(vnc, os.geteuid()))
            assert_no_qemu_tcp_listeners(process_seal(proc.pid))
            # PID/UID attestation is independent of filesystem permissions.
            verified_unix_peer(endpoints[0], process_seal(proc.pid), time.monotonic() + 5)
            verified_unix_peer(endpoints[1], process_seal(proc.pid), time.monotonic() + 5)
            isolated = os.environ.get("GASLUX_ISOLATED_WORKER") == "1"
            if isolated:
                # Unprivileged original-runner process probes both endpoints.
                # This protocol carries paths only, NEVER QMP/RFB commands.
                print(
                    "EXTERNAL_PROBE "
                    + json.dumps(
                        {"run_id": run_id, "qmp": str(qmp), "rfb": str(vnc)},
                        sort_keys=True,
                    ),
                    flush=True,
                )
                if sys.stdin.readline().strip() != "PROBE_DONE " + run_id:
                    raise Refusal("External isolation handshake missing or mismatched")
            else:
                if any(_outside_client(path, different_uid=True) != 13 for path in (qmp, vnc)):
                    raise Refusal("Cross-UID client reached a private QEMU endpoint")
                if any(_outside_client(path, different_uid=False) != 0 for path in (qmp, vnc)):
                    raise Refusal("Same-UID interference experiment was not reproducible")
            seal = QemuRunSeal(
                authority,
                process_seal(proc.pid),
                qmp,
                port,
                seal_file(iso),
                seal_file(cow),
                vnc_socket=vnc,
            )
            attestor = LocalQemuAttestor(seal)
            # Real-process negative: a second cooperating controller must not
            # acquire the same lease. This does NOT authorize guest input.
            with ControllerLease(sandbox, seal.process) as controller:
                controller.verify()
                try:
                    with ControllerLease(sandbox, seal.process):
                        raise Refusal("Second controller was admitted")
                except Refusal as exc:
                    if "second controller already holds the lease" not in str(exc):
                        raise
                controller.verify()
                print("QEMU stage: initial QMP witness", flush=True)
                idle_deadline = time.monotonic() + 3
                while True:
                    try:
                        attestor.verify(idle_deadline)
                        break
                    except Refusal as exc:
                        if (
                            "another VNC client" not in str(exc)
                            or time.monotonic() >= idle_deadline
                        ):
                            raise
                        time.sleep(0.05)
                surface = inspect_input_surface(seal.process, tuple(cmd), qmp, vnc)
                try:
                    surface.require_exclusive_input()
                except Refusal as exc:
                    if "RFB Unix endpoint remains accessible to same-UID processes" not in str(exc):
                        raise
                else:
                    raise Refusal("Unisolated QEMU input was accidentally authorized")
            png = None
            resolution = None
            # RFB observation is harmless. An unexpected screen size refuses a
            # read; it does not relax any identity or input validation.
            for candidate in RESOLUTIONS:
                try:
                    png = RfbReader(unix_socket=vnc).read_png(time.monotonic() + 4, candidate)
                    resolution = candidate
                    break
                except Refusal:
                    continue
            if png is None or resolution is None:
                raise Refusal("No complete RFB RAW framebuffer at reviewed probe resolutions")
            transport = ReadOnlyVncTransport(
                RfbReader(unix_socket=vnc), attestor, authority, resolution
            )
            print("QEMU stage: observation after initial RFB reader closed", flush=True)
            # RFB close notifications are asynchronous. Before opening another
            # read-only session, require QMP to prove the prior client is gone.
            idle_deadline = time.monotonic() + 3
            while True:
                try:
                    attestor.verify(idle_deadline)
                    break
                except Refusal as exc:
                    if "another VNC client" not in str(exc) or time.monotonic() >= idle_deadline:
                        raise
                    time.sleep(0.05)
            frame = transport.capture(time.monotonic() + 8)
            if frame.scale is not None or frame.passed_checks:
                raise Refusal("Read-only observation must not claim guest preconditions")
            # Run negative checks against THIS live process and QMP endpoint.
            # No negative check sends guest input or attaches any device.
            negative = []

            def must_refuse(name, check, reason: str):
                try:
                    check()
                except Refusal as exc:
                    if reason not in str(exc):
                        raise Refusal(f"Unexpected refusal reason for {name}: {exc}") from exc
                    negative.append(name)
                else:
                    raise Refusal(f"Live negative QEMU gate admitted drift: {name}")

            must_refuse(
                "process-start-mismatch",
                lambda: LocalQemuAttestor(
                    replace(
                        seal,
                        process=replace(seal.process, start_ticks=seal.process.start_ticks + 1),
                    )
                ).verify(time.monotonic() + 5),
                "QEMU process replaced or reconfigured",
            )
            must_refuse(
                "snapshot-mismatch",
                lambda: LocalQemuAttestor(
                    replace(seal, authority=replace(authority, snapshot_id="unauthorized-snapshot"))
                ).verify(time.monotonic() + 5),
                "Snapshot identity cannot be corroborated by QMP",
            )
            must_refuse(
                "qcow2-inode-mismatch",
                lambda: LocalQemuAttestor(
                    replace(seal, cow=replace(seal.cow, ino=seal.cow.ino + 1))
                ).verify(time.monotonic() + 5),
                "COW inode replaced",
            )
            must_refuse(
                "expired-deadline",
                lambda: attestor.verify(time.monotonic() - 1),
                "QEMU attestation deadline expired",
            )
            moved = qmp.with_name("qmp-temporarily-unavailable.sock")
            qmp.rename(moved)
            try:
                must_refuse(
                    "qmp-disconnected",
                    lambda: attestor.verify(time.monotonic() + 5),
                    "QMP or process inspection failed closed",
                )
            finally:
                moved.rename(qmp)
            # A second VNC reader is still an external input-capable client.
            # It sends only RFB protocol negotiation, NEVER pointer/keyboard data.
            # The QMP witness must refuse while that client is connected.
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as other:
                other.settimeout(3)
                other.connect(str(vnc))
                other.settimeout(3)

                def take_exact(size: int) -> bytes:
                    data = bytearray()
                    while len(data) < size:
                        part = other.recv(size - len(data))
                        if not part:
                            raise Refusal("Second VNC observation handshake truncated")
                        data.extend(part)
                    return bytes(data)

                if take_exact(12) != b"RFB 003.008\n":
                    raise Refusal("Unexpected second VNC protocol")
                other.sendall(b"RFB 003.008\n")
                security_count = take_exact(1)[0]
                if security_count not in range(1, 33) or b"\x01" not in take_exact(security_count):
                    raise Refusal("Second VNC handshake unavailable")
                other.sendall(b"\x01")
                if take_exact(4) != bytes(4):
                    raise Refusal("Second VNC security refusal")
                other.sendall(b"\x01")  # ClientInit shared, no input messages.
                take_exact(20)  # server width, height and pixel format
                name_length = int.from_bytes(take_exact(4), "big")
                if name_length > 256:
                    raise Refusal("Unbounded spectator VNC server name")
                take_exact(name_length)
                must_refuse(
                    "concurrent-vnc-client",
                    lambda: transport.capture(time.monotonic() + 5),
                    "Unbound graphical endpoint or another VNC client",
                )
            # The same-UID uncooperative client DID connect; this is a blocker.
            # The other client has closed; the normal session must recover
            # without authorizing or emitting any guest input.
            print("QEMU stage: post-concurrent-client QMP witness", flush=True)
            idle_deadline = time.monotonic() + 3
            while True:
                try:
                    attestor.verify(idle_deadline)
                    break
                except Refusal as exc:
                    if "another VNC client" not in str(exc) or time.monotonic() >= idle_deadline:
                        raise
                    time.sleep(0.05)
            # Deliberate drift on a SYNTHETIC test ISO only, after capturing
            # the original read-only frame. Never do this with upstream media.
            original_iso = iso.read_bytes()
            iso.write_bytes(b"X" + original_iso[1:])
            must_refuse(
                "iso-mutated",
                lambda: attestor.verify(time.monotonic() + 5),
                "ISO identity changed",
            )
            # The only proof published here is a *read-only* VM frame and
            # independently corroborated host/QMP identities. Zero guest clicks.
            location = evidence_root / run_id
            location.mkdir(mode=0o700)
            (location / "frame.png").write_bytes(frame.png)
            report = {
                "mode": "qemu-read-only-synthetic-media",
                "run_id": run_id,
                "sandbox_path": str(sandbox),
                "pid": seal.process.pid,
                "pid_start_ticks": seal.process.start_ticks,
                "cmdline_sha256": seal.process.command_sha256,
                "executable_dev": seal.process.executable_dev,
                "executable_ino": seal.process.executable_ino,
                "iso": asdict(identity),
                "iso_dev": seal.iso.dev,
                "iso_ino": seal.iso.ino,
                "qcow2_dev": seal.cow.dev,
                "qcow2_ino": seal.cow.ino,
                "snapshot": snapshot,
                "frame_sha256": digest(frame.png),
                "resolution": resolution,
                "qmp_identity_checked": True,
                "physical_block_fd_rejected": True,
                "guest_clicks": 0,
                "input_surface": asdict(surface),
                "input_authority_refused": True,
                "same_uid_external_rfb_connection": "admitted",
                "tcp_rfb_listener_configured": False,
                "qemu_tcp_listener_inventory": "no-listen-fds",
                "different_uid_rfb_qmp_connect": (
                    "external-host-probe" if isolated else "both-refused-eacces"
                ),
                "same_uid_rfb_qmp_connect": (
                    "dedicated-uid-other-process-not-excluded"
                    if isolated
                    else "both-admitted-blocker"
                ),
                "cooperative_controller_contention_refused": True,
                "live_negative_gates_refused": negative,
                "q4os_booted": False,
                "installer_navigated": False,
            }
            (location / "manifest.json").write_bytes(canonical(report))
            return report
        finally:
            if proc.poll() is None:
                proc.terminate()
            try:
                proc.communicate(timeout=8)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.communicate(timeout=4)
            if proc.poll() is None:
                raise Refusal("QEMU shutdown not confirmed")
            for endpoint in endpoints:
                clean_owned_endpoint(endpoint)
            if report is not None and location is not None:
                report["endpoint_cleanup_verified"] = True
                (location / "manifest.json").write_bytes(canonical(report))


def main() -> int:
    if os.name != "posix" or os.geteuid() == 0:
        raise Refusal("A non-root Linux runner is required")
    runner_temp = os.environ.get("RUNNER_TEMP")
    if not runner_temp:
        raise Refusal("A disposable runner scratch directory is required")
    root = Path(runner_temp).resolve(strict=True) / "observer-qemu-lab"
    root.mkdir(mode=0o700, exist_ok=False)
    runs = []
    try:
        for _ in range(2):
            runs.append(_one(root))
        if (
            len({r["run_id"] for r in runs}) != 2
            or len({r["sandbox_path"] for r in runs}) != 2
            or len({r["snapshot"] for r in runs}) != 2
            or len({(r["pid"], r["pid_start_ticks"]) for r in runs}) != 2
        ):
            raise Refusal("Independent VM execution identity was not demonstrated")
        result = {"runs": runs, "independent_vm_count": 2, "guest_input_count": 0}
        (root / "manifest.json").write_bytes(canonical(result))
        print(json.dumps(result, sort_keys=True))
        return 0
    except (Refusal, OSError, subprocess.SubprocessError) as exc:
        (root / "refusal.json").write_bytes(
            canonical({"status": "refused", "reason": str(exc), "completed_runs": len(runs)})
        )
        print(f"QEMU laboratory refused: {exc}", flush=True)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
