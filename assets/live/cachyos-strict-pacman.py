#!/usr/bin/env python3
"""Render a stricter CachyOS pacman policy; VM-only tmpfs output, no package writes.

The verified 260809 live ISO has a weak repository SigLevel. Do not copy it
into an installed system and do not use it for pacstrap. A new strict config
is independently constructed from a fixed repository allowlist. This is
lab staging only; it does not prove package signatures or Windows recovery.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

_RUN_ID = re.compile(r"[A-Za-z0-9_-]{12,100}\Z")
_REPO_MIRRORS = {"core": "mirrorlist", "extra": "mirrorlist", "cachyos": "cachyos-mirrorlist"}
_MIRROR_FILES = ("mirrorlist", "cachyos-mirrorlist")
_SERVER = re.compile(r"Server\s*=\s*(\S+)\s*\Z")
_SAFE_PATH = re.compile(r"/[A-Za-z0-9._~%+$/-]*\Z")
_FIXED_POLICY = "Required DatabaseOptional TrustedOnly"


class StrictConfigError(ValueError):
    """Cannot safely build the VM-only signed-repositories configuration."""


def require(ok: bool, message: str) -> None:
    if not ok:
        raise StrictConfigError(message)


def sha(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def safe_source(root: Path, relative: str) -> Path:
    candidate = root / relative
    require(
        candidate.is_file() and not candidate.is_symlink()
        and candidate.resolve().is_relative_to(root.resolve()),
        "untrusted source file: " + relative,
    )
    return candidate


def require_https(url: str) -> None:
    require(len(url) <= 2048 and all(ord(c) > 32 and ord(c) < 127 for c in url),
            "invalid mirror URL")
    parsed = urlsplit(url)
    require(
        parsed.scheme == "https" and bool(parsed.hostname)
        and parsed.username is None and parsed.password is None
        and not parsed.query and not parsed.fragment
        and _SAFE_PATH.fullmatch(parsed.path) is not None
        and parsed.netloc == parsed.netloc.lower()
        and ".." not in parsed.path.split("/"),
        "mirror must be an HTTPS URL without credentials, injection or traversal",
    )
    try:
        port = parsed.port
    except ValueError as error:
        raise StrictConfigError("invalid mirror port") from error
    require(port is None or 1 <= port <= 65535, "invalid mirror port")


def filter_mirrors(content: str) -> str:
    require(isinstance(content, str) and 0 < len(content) <= 256_000,
            "missing or oversized mirrorlist")
    servers: list[str] = []
    for line in content.splitlines():
        value = line.strip()
        if not value or value.startswith("#"):
            continue
        matched = _SERVER.fullmatch(value)
        require(matched is not None, "unexpected active mirrorlist directive")
        url = matched.group(1)
        # Omit HTTP/FTP mirrors, but never permit an invalid HTTPS URL.
        if not url.startswith("https://"):
            require(url.startswith(("http://", "ftp://")),
                    "unexpected non-HTTPS mirror scheme")
            continue
        require_https(url)
        if url not in servers:
            servers.append(url)
    require(1 <= len(servers) <= 128, "no usable or too many HTTPS mirrors")
    return "".join("Server = " + item + "\n" for item in servers)


def config_for(mirrors_prefix: str) -> str:
    require(
        mirrors_prefix in ("/etc/pacman.d",) or re.fullmatch(
            r"/run/gaslux-pacman-[A-Za-z0-9_-]{12,100}", mirrors_prefix
        ) is not None,
        "unsafe pacman mirror directory",
    )
    lines = [
        "# Generated by Gaslux for a disposable QEMU VM, NOT production authorization",
        "[options]",
        "Architecture = auto",
        "CheckSpace",
        "SigLevel = " + _FIXED_POLICY,
        "LocalFileSigLevel = Required TrustedOnly",
        "RemoteFileSigLevel = Required TrustedOnly",
    ]
    for repo, mirror in _REPO_MIRRORS.items():
        lines.extend([
            "",
            "[" + repo + "]",
            "SigLevel = " + _FIXED_POLICY,
            "Include = " + mirrors_prefix + "/" + mirror,
        ])
    return "\n".join(lines) + "\n"


def render(root: Path, run_id: str) -> dict[str, Any]:
    require(isinstance(run_id, str) and _RUN_ID.fullmatch(run_id) is not None,
            "invalid transaction identifier")
    require(root.is_absolute() and root.is_dir() and not root.is_symlink()
            and root.resolve() == root,
            "live root must be an explicit canonical directory")
    os_release = safe_source(root, "etc/os-release").read_text(encoding="utf-8")
    require("ID=cachyos" in os_release.splitlines()
            and "IMAGE_ID=cachyos" in os_release.splitlines()
            and "IMAGE_VERSION=2026.08.09" in os_release.splitlines(),
            "unsupported CachyOS Archiso live identity")
    live_pacman = safe_source(root, "etc/pacman.conf")
    require(live_pacman.stat().st_size > 0, "missing live pacman configuration")
    mirror_data = {
        file: filter_mirrors(safe_source(root, "etc/pacman.d/" + file).read_text(
            encoding="utf-8"
        ))
        for file in _MIRROR_FILES
    }
    output_path = "/run/gaslux-pacman-" + run_id
    installing = config_for(output_path)
    installed = config_for("/etc/pacman.d")
    return {
        "runId": run_id,
        "generatedFromPinnedProfile": "cachyos-260809",
        "sourceLivePolicyTrusted": False,
        "packageSignaturesMandatory": True,
        "labOnly": True,
        "windowsInstallerStable": False,
        "pacstrapExecuted": False,
        "installedBootVerified": False,
        "installerConfig": installing,
        "installedTargetConfig": installed,
        "mirrorlist": mirror_data["mirrorlist"],
        "cachyos-mirrorlist": mirror_data["cachyos-mirrorlist"],
        "installerConfigSha256": sha(installing),
        "targetConfigSha256": sha(installed),
        "archMirrorsSha256": sha(mirror_data["mirrorlist"]),
        "cachyosMirrorsSha256": sha(mirror_data["cachyos-mirrorlist"]),
    }


def check_vm_environment() -> None:
    require(os.geteuid() == 0, "VM lab configuration requires root")
    require(
        os.environ.get("GASLUX_DISPOSABLE_VM") == "I_ACCEPT_DISPOSABLE_VM_ONLY",
        "missing explicit disposable-VM consent",
    )
    output = subprocess.run(
        ["systemd-detect-virt", "--vm"], capture_output=True,
        text=True, check=False, timeout=8
    )
    require(output.returncode == 0 and output.stdout.strip() in {"kvm", "qemu"},
            "physical devices and non-QEMU virtual machines are forbidden")
    fs = subprocess.run(
        ["findmnt", "-rn", "-M", "/run", "-o", "FSTYPE"],
        capture_output=True, text=True, check=False, timeout=8
    )
    require(fs.returncode == 0 and fs.stdout.strip() == "tmpfs",
            "only an exact ephemeral /run tmpfs is acceptable")
    require(Path("/run").is_dir() and not Path("/run").is_symlink(),
            "unsafe lab tmpfs root")


def prepare_vm(result: dict[str, Any]) -> Path:
    check_vm_environment()
    dest = Path("/run/gaslux-pacman-" + result["runId"])
    # Refuse reuse from another failed or interrupted transaction.
    dest.mkdir(mode=0o700, exist_ok=False)
    values = {
        "pacman-install.conf": result["installerConfig"],
        "pacman-target.conf": result["installedTargetConfig"],
        "mirrorlist": result["mirrorlist"],
        "cachyos-mirrorlist": result["cachyos-mirrorlist"],
    }
    for filename, content in values.items():
        # x is O_EXCL; all files are written only inside the new /run tmpfs dir.
        with (dest / filename).open("x", encoding="utf-8") as stream:
            stream.write(content)
    return dest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("/"))
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--prepare-vm", action="store_true")
    args = parser.parse_args(argv)
    try:
        report = render(args.root, args.run_id)
        if args.prepare_vm:
            require(args.root == Path("/"), "VM installation requires the running Archiso root")
            prepared = prepare_vm(report)
        else:
            prepared = None
        summary = {k: v for k, v in report.items()
                   if k not in {"installerConfig", "installedTargetConfig",
                                "mirrorlist", "cachyos-mirrorlist"}}
        summary.update({
            "ok": True,
            "preparedVmTmpfsDirectory": str(prepared) if prepared else None,
            "readyForProduction": False,
            "trustedPackageDownloadTested": False,
        })
    except (StrictConfigError, OSError, ValueError, UnicodeError,
            subprocess.TimeoutExpired) as error:
        print(json.dumps({"ok": False, "error": str(error)}), file=sys.stderr)
        return 1
    print(json.dumps(summary, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
